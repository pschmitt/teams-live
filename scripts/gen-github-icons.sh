#!/usr/bin/env bash
# Regenerates src/github-icons-small.mjs (the GitHub icons of list rows) from
# the upstream @primer/octicons package (MIT). Needs npm, tar, jq and
# ImageMagick (with the librsvg delegate).
#
# Usage: scripts/gen-github-icons.sh [VERSION]   (default: 19.15.1)

set -euo pipefail

version="${1:-19.15.1}"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

(cd "$work" && npm pack --silent "@primer/octicons@${version}" >/dev/null 2>&1 && mkdir pkg && tar -xzf ./*.tgz -C pkg)
src="$work/pkg/package/build/svg"
pkg_version="$(jq -r .version "$work/pkg/package/package.json")"
[[ "$(jq -r .license "$work/pkg/package/package.json")" == "MIT" ]] || {
  echo "unexpected license" >&2
  exit 1
}

# name:file:colour; green and gray legible on light and dark themes
icons=(
  pull-request-open:git-pull-request-16:#2da44e
  pull-request-draft:git-pull-request-draft-16:#8a8a92
  mark:mark-github-16:#8a8a92
)

out="$root/src/github-icons-small.mjs"
{
  cat <<HEADER
// GitHub icons for list rows: 32x32 palette PNG data URIs, shown at 16px
// (generated by scripts/gen-github-icons.sh, do not edit by hand).
//
// The glyphs come from @primer/octicons ${pkg_version} (MIT, Copyright (c) GitHub Inc.).

export const GITHUB_ICONS_SMALL = {
HEADER
  for spec in "${icons[@]}"; do
    IFS=: read -r name file colour <<<"$spec"
    sed "s/<path /<path fill=\"${colour}\" /g" "$src/${file}.svg" >"$work/${name}.svg"
    magick -background none -density 768 "$work/${name}.svg" -resize 32x32 \
      -depth 8 -strip -define png:compression-level=9 "PNG8:$work/${name}.png"
    printf "  '%s':\n    'data:image/png;base64,%s',\n" "$name" "$(base64 -w0 "$work/${name}.png")"
  done
  echo '};'
} >"$out"
echo "wrote $out"
